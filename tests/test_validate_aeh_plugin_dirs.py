"""AEH validation requires plugin_dirs skills when declared."""

from pathlib import Path

from abevalflow.schemas import EvalEngine
from scripts.validate import validate_submission
from tests.test_validate_aeh import VALID_EVAL_YAML, create_aeh_submission


def test_aeh_plugin_dirs_missing_skills_fails(tmp_path: Path):
    eval_yaml = {
        **VALID_EVAL_YAML,
        "skill": "demo-skill",
        "runner": {"type": "claude-code", "plugin_dirs": ["skills"]},
    }
    create_aeh_submission(tmp_path, eval_yaml_content=eval_yaml)
    errors = validate_submission(tmp_path, eval_engine=EvalEngine.AEH)
    assert any("plugin_dirs" in e and "missing" in e for e in errors)


def test_aeh_plugin_dirs_with_named_skill_passes(tmp_path: Path):
    eval_yaml = {
        **VALID_EVAL_YAML,
        "skill": "demo-skill",
        "runner": {"type": "claude-code", "plugin_dirs": ["skills"]},
    }
    create_aeh_submission(tmp_path, eval_yaml_content=eval_yaml)
    skill = tmp_path / "skills" / "demo-skill"
    skill.mkdir(parents=True)
    (skill / "SKILL.md").write_text("---\nname: demo-skill\n---\n")
    errors = validate_submission(tmp_path, eval_engine=EvalEngine.AEH)
    assert not any("plugin_dirs" in e or "SKILL.md" in e for e in errors)


def test_aeh_plugin_dirs_mcp_only_no_skill_passes(tmp_path: Path):
    """A plugin_dirs entry with only mcps.json (no SKILL.md anywhere) is
    valid as long as this config has no execution.skill/top-level skill --
    e.g. a pairwise control arm getting MCP tool access without any skill
    guidance (submissions/rh-sre/cve-validation's eval-control.yaml ->
    rh-sre-mcp-only/mcps.json, generated by scripts/swap_mock_mcp.py)."""
    eval_yaml = {
        **VALID_EVAL_YAML,
        "runner": {"type": "claude-code", "plugin_dirs": ["mcp-only"]},
    }
    create_aeh_submission(tmp_path, eval_yaml_content=eval_yaml)
    mcp_only = tmp_path / "mcp-only"
    mcp_only.mkdir(parents=True)
    (mcp_only / "mcps.json").write_text('{"mcpServers": {}}')
    errors = validate_submission(tmp_path, eval_engine=EvalEngine.AEH)
    assert not any("plugin_dirs" in e or "SKILL.md" in e for e in errors)


def test_aeh_plugin_dirs_mcp_only_sibling_not_yet_generated_passes(tmp_path: Path):
    """A "<pack>-mcp-only" plugin_dirs entry that doesn't exist on disk yet
    (scripts/swap_mock_mcp.py generates it before validate normally runs,
    but validate tolerates it missing too, e.g. for standalone/local
    validate-only runs) is NOT a 'missing' error when no skill is set."""
    eval_yaml = {
        **VALID_EVAL_YAML,
        "runner": {"type": "claude-code", "plugin_dirs": ["../rh-sre-mcp-only"]},
    }
    create_aeh_submission(tmp_path, eval_yaml_content=eval_yaml)
    errors = validate_submission(tmp_path, eval_engine=EvalEngine.AEH)
    assert not any("plugin_dirs" in e for e in errors)


def test_aeh_plugin_dirs_missing_dir_not_matching_mcp_only_still_fails(tmp_path: Path):
    """A missing plugin_dirs entry that does NOT match the "-mcp-only"
    naming convention is still a hard error, even with no skill set -- the
    carve-out above is narrowly scoped to that one naming convention."""
    eval_yaml = {
        **VALID_EVAL_YAML,
        "runner": {"type": "claude-code", "plugin_dirs": ["totally-missing"]},
    }
    create_aeh_submission(tmp_path, eval_yaml_content=eval_yaml)
    errors = validate_submission(tmp_path, eval_engine=EvalEngine.AEH)
    assert any("plugin_dirs" in e and "missing" in e for e in errors)


def test_aeh_plugin_dirs_no_skill_no_mcp_still_fails(tmp_path: Path):
    """A plugin_dirs entry with neither SKILL.md nor mcps.json is still an
    error even with no execution.skill set -- it's not a valid MCP-only
    entry, just an empty/broken one."""
    eval_yaml = {
        **VALID_EVAL_YAML,
        "runner": {"type": "claude-code", "plugin_dirs": ["empty"]},
    }
    create_aeh_submission(tmp_path, eval_yaml_content=eval_yaml)
    (tmp_path / "empty").mkdir(parents=True)
    errors = validate_submission(tmp_path, eval_engine=EvalEngine.AEH)
    assert any("plugin_dirs" in e and "SKILL.md" in e for e in errors)


def test_aeh_plugin_dirs_execution_skill_with_mcp_only_still_fails(tmp_path: Path):
    """execution.skill set but plugin_dirs is MCP-only (no SKILL.md) must
    still fail -- Harbor would get "/skill-name" with nothing to resolve
    it. MCP-only tolerance only applies when NO skill is being invoked."""
    eval_yaml = {
        **VALID_EVAL_YAML,
        "execution": {"skill": "demo-skill", "arguments": "{{ input.prompt }}"},
        "runner": {"type": "claude-code", "plugin_dirs": ["mcp-only"]},
    }
    create_aeh_submission(tmp_path, eval_yaml_content=eval_yaml)
    mcp_only = tmp_path / "mcp-only"
    mcp_only.mkdir(parents=True)
    (mcp_only / "mcps.json").write_text('{"mcpServers": {}}')
    errors = validate_submission(tmp_path, eval_engine=EvalEngine.AEH)
    assert any("plugin_dirs" in e and "SKILL.md" in e for e in errors)
