"""Render a content-addressed immutable ConfigMap from trusted mock descriptors."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import yaml

from abevalflow.mcp_ci import descriptor


def render(catalog):
    catalog = Path(catalog)
    files = sorted(catalog.glob("*.yaml"))
    if not files:
        raise ValueError("trusted mock catalog is empty")
    for path in files:
        descriptor(path.stem, catalog)
    data = {path.name: path.read_text() for path in files}
    digest = hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()
    return {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {
            "name": "harbor-mcp-catalog-" + digest[:16],
            "annotations": {"abevalflow.io/catalog-sha256": digest},
        },
        "immutable": True,
        "data": data,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=Path("config/mcp-mocks"))
    parser.add_argument("--output", type=Path, default=Path("config/harbor-mcp-catalog.yaml"))
    args = parser.parse_args()
    result = render(args.catalog)
    args.output.write_text(
        "# Generated by python -m scripts.render_mcp_catalog; do not edit.\n" + yaml.safe_dump(result, sort_keys=False)
    )
    print(result["metadata"]["name"])


if __name__ == "__main__":
    main()
