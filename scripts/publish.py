def upload_scaffolded_configs(
    workspace_root: Path,
    submission_name: str,
    prefix: str,
    endpoint: str,
    access_key: str,
    secret_key: str,
    bucket: str = "ab-eval-reports",
    secure: bool | None = None,
) -> int:
    """Upload scaffolded configs and review artifacts to MinIO under scaffolded/.

    Uploads task.toml, test.sh, Dockerfile for each variant, plus harbor
    eval configs and AI review output when available.
    """
    from minio import Minio

    parsed = urlparse(endpoint)
    host = parsed.netloc or parsed.path
    if secure is None:
        secure = parsed.scheme == "https"

    client = Minio(host, access_key=access_key, secret_key=secret_key, secure=secure)

    uploaded = 0
    variant_files = ("task.toml", "tests/test.sh", "environment/Dockerfile")

    for variant in ("treatment", "control"):
        variant_dir = workspace_root / f"tasks-{variant}" / submission_name
        if not variant_dir.is_dir():
            logger.warning("Scaffolded dir not found: %s", variant_dir)
            continue
        for rel_path in variant_files:
            fpath = variant_dir / rel_path
            if not fpath.is_file():
                continue
            object_name = f"{prefix}/scaffolded/{variant}/{Path(rel_path).name}"
            try:
                client.fput_object(bucket, object_name, str(fpath))
                uploaded += 1
            except Exception as exc:
                logger.warning("Failed to upload %s: %s", fpath, exc)

    eval_configs_dir = workspace_root / "_eval-configs"
    if eval_configs_dir.is_dir():
        for fpath in sorted(eval_configs_dir.glob("*.yaml")):
            masked = re.sub(r"(API_KEY:\s*)(\S+)", r"\1***", fpath.read_text())
            masked_path = fpath.parent / f".masked_{fpath.name}"
            masked_path.write_text(masked)
            object_name = f"{prefix}/scaffolded/{fpath.name}"
            try:
                client.fput_object(bucket, object_name, str(masked_path))
                uploaded += 1
            except Exception as exc:
                logger.warning("Failed to upload %s: %s", fpath, exc)
            finally:
                masked_path.unlink(missing_ok=True)

    ai_review_path = workspace_root / "_ai_review.json"
    if ai_review_path.is_file():
        object_name = f"{prefix}/scaffolded/ai_review.json"
        try:
            client.fput_object(bucket, object_name, str(ai_review_path))
            uploaded += 1
        except Exception as exc:
            logger.warning("Failed to upload AI review: %s", exc)

    submission_dir = workspace_root / "submissions" / submission_name
    generated_candidates = [
        # Harbor-generated files
        (submission_dir / "instruction.md", "instruction.md"),
        (submission_dir / "tests" / "test_outputs.py", "test_outputs.py"),
        (submission_dir / "tests" / "llm_judge.py", "llm_judge.py"),
        (submission_dir / "scenario_brief.json", "scenario_brief.json"),
        # ASE-generated files
        (submission_dir / "evals" / "evals.json", "evals.json"),
    ]
    for filepath, name in generated_candidates:
        if not filepath.is_file():
            continue
        if not _is_ai_generated_artifact(filepath, name):
            continue
        object_name = f"{prefix}/generated/{name}"
        try:
            client.fput_object(bucket, object_name, str(filepath))
            uploaded += 1
        except Exception as exc:
            logger.warning("Failed to upload generated file %s: %s", filepath, exc)

    logger.info("Uploaded %d config/generated files to s3://%s/%s/", uploaded, bucket, prefix)
    return uploaded


def promote_to_quay(
    treatment_image_ref: str,
    submission_name: str,
    commit_sha: str,
    quay_repo: str,
    ttl_days: int = 7,
) -> bool:
    """Copy the treatment image from internal registry to Quay.io.

    Uses skopeo to copy the image. Returns True on success.
    """
    quay_tag = f"{quay_repo}/{submission_name}:treatment-{commit_sha[:12]}"

    cmd = [
        "skopeo",
        "copy",
        "--src-tls-verify=false",
        f"docker://{treatment_image_ref}",
        f"docker://{quay_tag}",
    ]

    logger.info("Promoting to Quay: %s -> %s (ttl=%dd)", treatment_image_ref, quay_tag, ttl_days)

    try:
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
        if result.returncode != 0:
            logger.error("skopeo copy failed: %s", result.stderr)
            return False
        logger.info("Image promoted to %s", quay_tag)
        return True
    except FileNotFoundError:
        logger.error("skopeo not found — cannot promote image")
        return False
    except subprocess.TimeoutExpired:
        logger.error("skopeo copy timed out after 300s")
        return False


def post_pr_comment(
    repo_name: str,
    pr_number: str,
    submission_name: str,
    report_dir: Path,
    github_token: str | None = None,
) -> bool:
    """Post evaluation summary as a GitHub PR comment.

    Uses the GitHub REST API via ``urllib`` (no ``gh`` CLI required).
    ``github_token`` falls back to the ``GITHUB_TOKEN`` environment variable.

    If scorecard.json exists, its recommendation takes precedence over report.json.
    """
    import os

    token = github_token or os.environ.get("GITHUB_TOKEN", "")
    if not token:
        logger.error("GITHUB_TOKEN not set — cannot post PR comment")
        return False

    report_path = report_dir / "report.json"
    if not report_path.exists():
        logger.warning("No report.json found, skipping PR comment")
        return False

    try:
        report = json.loads(report_path.read_text())
    except (json.JSONDecodeError, OSError) as exc:
        logger.error("Failed to read report.json: %s", exc)
        return False

    summary = report.get("summary", {})
    treatment = summary.get("treatment", {})
    control = summary.get("control", {})
    recommendation = summary.get("recommendation", "unknown").upper()
    uplift = summary.get("uplift", 0.0)
    provenance = report.get("provenance", {})

    # Check for scorecard and use its recommendation if available
    scorecard_section = ""
    scorecard_path = report_dir / "scorecard.json"
    if scorecard_path.exists():
        try:
            scorecard = json.loads(scorecard_path.read_text())
            sc_recommendation = scorecard.get("recommendation", "").upper()
            sc_reason = scorecard.get("recommendation_reason", "")
            gates_passed = scorecard.get("gates_passed", 0)
            gates_failed = scorecard.get("gates_failed", 0)

            # Scorecard recommendation takes precedence
            if sc_recommendation:
                recommendation = sc_recommendation

            # Build gate summary
            gates = scorecard.get("gates", [])
            gate_lines = []
            for gate in gates:
                status = "✅" if gate.get("passed") else "❌"
                name = gate.get("gate_name", "unknown")
                score = gate.get("score", 0.0)
                mode = gate.get("mode", "warn")
                gate_lines.append(f"| {name} | {status} | {score:.2f} | {mode} |")

            if gate_lines:
                gate_table = "\n".join(gate_lines)
                scorecard_section = (
                    f"\n### Unified Scorecard\n\n"
                    f"**Recommendation:** {sc_recommendation} ({sc_reason})\n\n"
                    f"| Gate | Status | Score | Mode |\n"
                    f"|------|--------|-------|------|\n"
                    f"{gate_table}\n\n"
                    f"**Gates:** {gates_passed} passed, {gates_failed} failed\n"
                )
        except (json.JSONDecodeError, OSError) as exc:
            logger.warning("Failed to read scorecard.json: %s", exc)

    comment_body = (
        f"## AB Evaluation Results: `{submission_name}`\n\n"
        f"| Metric | Treatment | Control |\n"
        f"|--------|-----------|--------|\n"
        f"| Trials | {treatment.get('n_trials', '?')} | {control.get('n_trials', '?')} |\n"
        f"| Passed | {treatment.get('n_passed', '?')} | {control.get('n_passed', '?')} |\n"
        f"| Pass Rate | {treatment.get('pass_rate', 0):.2%} | {control.get('pass_rate', 0):.2%} |\n"
        f"| Mean Reward | {treatment.get('mean_reward', 'N/A')} | {control.get('mean_reward', 'N/A')} |\n\n"
        f"**Uplift:** {uplift:+.4f}  \n"
        f"**Recommendation:** {recommendation}  \n"
        f"**Pipeline Run:** `{provenance.get('pipeline_run_id', 'N/A')}`  \n"
        f"**Commit:** `{provenance.get('commit_sha', 'N/A')[:12] if provenance.get('commit_sha') else 'N/A'}`\n"
        f"{scorecard_section}"
    )

    url = f"https://api.github.com/repos/{repo_name}/issues/{pr_number}/comments"
    payload = json.dumps({"body": comment_body}).encode()
    req = urllib.request.Request(
        url,
        data=payload,
        headers={
            "Authorization": f"token {token}",
            "Accept": "application/vnd.github+json",
            "Content-Type": "application/json",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            if 200 <= resp.status < 300:
                logger.info("Posted PR comment to %s#%s", repo_name, pr_number)
                return True
            logger.error("GitHub API returned %d", resp.status)
            return False
    except Exception as exc:
        logger.error("Failed to post PR comment: %s", exc)
        return False


def cleanup_images(
    image_refs: list[str],
    registry_url: str = "image-registry.openshift-image-registry.svc:5000",
) -> int:
    """Delete images from the OpenShift internal registry.

    For digest refs (``@sha256:…``), deletes the parent ImageStream so all
    tags and layers are removed.  For tag refs, deletes the specific
    ImageStreamTag.  Returns the number of successfully deleted resources.
    """
    deleted = 0
    seen_imagestreams: set[str] = set()

    for ref in image_refs:
        stripped = ref.replace(f"{registry_url}/", "")
        parts = stripped.split("/", 1)
        if len(parts) != 2:
            logger.warning("Cannot parse image ref for cleanup: %s", ref)
            continue

        namespace = parts[0]
        name_part = parts[1]

        if "@" in name_part:
            is_name = name_part.split("@")[0]
            key = f"{namespace}/{is_name}"
            if key in seen_imagestreams:
                continue
            seen_imagestreams.add(key)
            cmd = ["oc", "delete", "imagestream", is_name, "-n", namespace, "--ignore-not-found"]
        else:
            cmd = ["oc", "delete", "istag", name_part, "-n", namespace]

        try:
            result = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
            if result.returncode == 0:
                logger.info("Deleted %s in %s", name_part, namespace)
                deleted += 1
            else:
                logger.warning("Failed to delete %s: %s", name_part, result.stderr.strip())
        except (FileNotFoundError, subprocess.TimeoutExpired) as exc:
            logger.warning("Cleanup failed for %s: %s", ref, exc)

    return deleted


def main() -> int:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )
    parser = argparse.ArgumentParser(description="Publish evaluation artifacts")
    parser.add_argument("--report-dir", type=Path, required=True)
    parser.add_argument("--submission-name", type=str, required=True)
    parser.add_argument("--pipeline-run-id", type=str, required=True)
    parser.add_argument("--recommendation", type=str, required=True, help="'pass' or 'fail' from the analyze step")
    parser.add_argument("--treatment-image-ref", type=str, default="")
    parser.add_argument("--control-image-ref", type=str, default="")
    parser.add_argument("--commit-sha", type=str, default="")
    parser.add_argument(
        "--uplift-threshold",
        type=float,
        default=-1.0,
        help="Minimum uplift for Quay promotion. -1.0 disables promotion.",
    )
    parser.add_argument(
        "--quay-repo", type=str, default="", help="Quay.io repo for image promotion (e.g. quay.io/myorg)"
    )
    parser.add_argument("--quay-ttl-days", type=int, default=7)
    parser.add_argument("--repo-name", type=str, default="", help="GitHub repo (org/name) for PR comment")
    parser.add_argument("--pr-number", type=str, default="", help="PR number for GitHub comment")
    parser.add_argument(
        "--results-dir", type=Path, default=None, help="Path to results dir (Harbor or ASE) for debug artifact upload"
    )
    parser.add_argument(
        "--eval-engine",
        type=str,
        default="harbor",
        choices=["harbor", "ase", "mcpchecker", "a2a", "aeh", "aeh_openshell_openclaw", "both"],
        help="Evaluation engine used — determines debug artifact layout",
    )
    parser.add_argument(
        "--workspace-root", type=Path, default=None, help="Workspace root for uploading scaffolded configs"
    )
    parser.add_argument(
        "--minio-endpoint", type=str, default=None, help="MinIO endpoint (default: MINIO_ENDPOINT env var)"
    )
    parser.add_argument("--minio-bucket", type=str, default="ab-eval-reports")
    parser.add_argument(
        "--report-prefix", type=str, default="", help="Pre-computed MinIO prefix (skips generating new timestamp)"
    )
    args = parser.parse_args()

    import os

    minio_endpoint = args.minio_endpoint or os.environ.get("MINIO_ENDPOINT", "")
    minio_access_key = os.environ.get("MINIO_ACCESS_KEY", "")
    minio_secret_key = os.environ.get("MINIO_SECRET_KEY", "")

    upload_ok = True
    success = True

    # --- 1. Upload reports to MinIO ---
    if minio_endpoint and minio_access_key:
        prefix = upload_reports(
            report_dir=args.report_dir,
            submission_name=args.submission_name,
            pipeline_run_id=args.pipeline_run_id,
            endpoint=minio_endpoint,
            access_key=minio_access_key,
            secret_key=minio_secret_key,
            bucket=args.minio_bucket,
            report_prefix=args.report_prefix or None,
        )
        if prefix:
            logger.info("Reports uploaded to s3://%s/%s/", args.minio_bucket, prefix)
        else:
            logger.warning("No report files uploaded — continuing with debug artifacts")
            prefix = args.report_prefix or _build_artifact_prefix(
                args.submission_name,
                args.pipeline_run_id,
            )
        if args.results_dir:
            if args.eval_engine == "mcpchecker":
                _upload_fn = upload_mcpchecker_debug_artifacts
            elif args.eval_engine in ("ase", "both"):
                _upload_fn = upload_ase_debug_artifacts
            elif args.eval_engine in ("aeh", "aeh_openshell_openclaw"):
                _upload_fn = upload_aeh_debug_artifacts
            else:
                # harbor, a2a — treatment/control Harbor trial layout
                _upload_fn = upload_debug_artifacts
            _upload_fn(
                results_dir=args.results_dir,
                prefix=prefix,
                endpoint=minio_endpoint,
                access_key=minio_access_key,
                secret_key=minio_secret_key,
                bucket=args.minio_bucket,
            )
        # AEH harness run dirs (summary.yaml, report.html, cases/, …)
        # live under reports/<skill>/ — upload for both single and pairwise.
        if prefix and args.eval_engine in ("aeh", "aeh_openshell_openclaw"):
            upload_aeh_run_artifacts(
                report_dir=args.report_dir,
                prefix=prefix,
                endpoint=minio_endpoint,
                access_key=minio_access_key,
                secret_key=minio_secret_key,
                bucket=args.minio_bucket,
                workspace_root=args.workspace_root,
            )
        if prefix and args.workspace_root:
            upload_scaffolded_configs(
                workspace_root=args.workspace_root,
                submission_name=args.submission_name,
                prefix=prefix,
                endpoint=minio_endpoint,
                access_key=minio_access_key,
                secret_key=minio_secret_key,
                bucket=args.minio_bucket,
            )
    else:
        logger.warning("MinIO not configured — skipping report upload")

    # --- 2. Quay.io promotion (if enabled) ---
    if args.uplift_threshold > -1.0 and args.recommendation == "pass" and args.treatment_image_ref and args.quay_repo:
        report_path = args.report_dir / "report.json"
        uplift = 0.0
        if report_path.exists():
            try:
                data = json.loads(report_path.read_text())
                uplift = data.get("summary", {}).get("uplift", 0.0)
            except (json.JSONDecodeError, OSError):
                pass

        if uplift >= args.uplift_threshold:
            ok = promote_to_quay(
                treatment_image_ref=args.treatment_image_ref,
                submission_name=args.submission_name,
                commit_sha=args.commit_sha,
                quay_repo=args.quay_repo,
                ttl_days=args.quay_ttl_days,
            )
            if not ok:
                success = False
        else:
            logger.info(
                "Uplift %.4f below threshold %.4f — skipping Quay promotion",
                uplift,
                args.uplift_threshold,
            )
    else:
        logger.info("Quay promotion disabled or not applicable")

    # --- 3. GitHub PR comment ---
    if args.repo_name and args.pr_number:
        post_pr_comment(
            repo_name=args.repo_name,
            pr_number=args.pr_number,
            submission_name=args.submission_name,
            report_dir=args.report_dir,
        )
    else:
        logger.info("No repo-name/pr-number — skipping PR comment")

    # --- 4. Cleanup internal registry images (only after successful upload) ---
    image_refs = [r for r in [args.treatment_image_ref, args.control_image_ref] if r]
    if image_refs and upload_ok:
        cleaned = cleanup_images(image_refs)
        logger.info("Cleaned up %d/%d images", cleaned, len(image_refs))
    elif image_refs and not upload_ok:
        logger.warning("Skipping cleanup — reports were not successfully uploaded")

    return 0 if success else 1


if __name__ == "__main__":
    sys.exit(main())
